#!/usr/bin/env node
/**
 * Fingerprints every function of the stock classic Shadow MD (Eebel) in
 * test/fixtures/classic-stock into lib/classic-reference.js. The migrator compares a
 * builder's sketch with it to find hand-edited and added functions.
 *   node scripts/build-classic-reference.js
 */
"use strict";
const fs = require("fs");
const path = require("path");
const T = require("../lib/sketch-text.js");

const here = path.join(__dirname, "..");
const dir = path.join(here, "test", "fixtures", "classic-stock");
const files = fs
  .readdirSync(dir)
  .filter((f) => /\.(ino|h)$/.test(f))
  .sort()
  .map((name) => ({ name, text: fs.readFileSync(path.join(dir, name), "utf8") }));
const functions = {};
for (const f of T.splitFunctions(files)) functions[f.key] = T.fnv1a(T.normalizeBody(f.body));

const ref = { eebel: { source: "Eebel/SHADOW_MD_EEBEL master (test/fixtures/classic-stock)", functions } };
const out =
  "/* Generated by scripts/build-classic-reference.js from test/fixtures/classic-stock, do not edit. */\n" +
  "(function (root) {\n" +
  '  "use strict";\n' +
  "  const api = " + JSON.stringify(ref, null, 2).replace(/\n/g, "\n  ") + ";\n" +
  '  if (typeof module !== "undefined" && module.exports) module.exports = api;\n' +
  "  else root.ClassicReference = api;\n" +
  "})(this);\n";
fs.writeFileSync(path.join(here, "lib", "classic-reference.js"), out);
console.log("lib/classic-reference.js: " + Object.keys(functions).length + " functions");
