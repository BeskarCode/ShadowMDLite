#!/usr/bin/env node
/**
 * Packs ../ShadowMDLite.ino into lib/lite-base.js for the classic to Lite migrator, so the
 * console can write a migrated sketch without internet. Run it whenever ShadowMDLite.ino
 * changes, before publishing the console:   node scripts/build-lite-base.js
 */
"use strict";
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const here = path.join(__dirname, "..");
const ino = path.join(here, "..", "ShadowMDLite.ino");
const text = fs.readFileSync(ino, "utf8").replace(/\r\n?/g, "\n");
let version = "unknown";
try {
  version = execSync("git describe --always --dirty", { cwd: here }).toString().trim();
} catch (_) {}

const out =
  "/* Generated by scripts/build-lite-base.js from ShadowMDLite.ino, do not edit. */\n" +
  "(function (root) {\n" +
  '  "use strict";\n' +
  "  const api = { version: " + JSON.stringify(version) + ", text: " + JSON.stringify(text) + " };\n" +
  '  if (typeof module !== "undefined" && module.exports) module.exports = api;\n' +
  "  else root.LiteBase = api;\n" +
  "})(this);\n";
fs.writeFileSync(path.join(here, "lib", "lite-base.js"), out);
console.log("lib/lite-base.js: ShadowMDLite " + version + ", " + text.length + " characters");
