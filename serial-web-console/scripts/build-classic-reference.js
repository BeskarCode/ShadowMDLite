#!/usr/bin/env node
/**
 * Fingerprints every function of the stock classic Shadow MD versions into
 * lib/classic-reference.js: Eebel's (test/fixtures/classic-stock) and Vint43's original
 * SHADOW_MD (test/fixtures/classic-vint43). The migrator picks the version that matches a
 * builder's sketch best and compares with it to find hand-edited and added functions.
 *   node scripts/build-classic-reference.js
 */
"use strict";
const fs = require("fs");
const path = require("path");
const T = require("../lib/sketch-text.js");

const here = path.join(__dirname, "..");
function fingerprint(fixture) {
  const dir = path.join(here, "test", "fixtures", fixture);
  const files = fs
    .readdirSync(dir)
    .filter((f) => /\.(ino|h)$/.test(f))
    .sort()
    .map((name) => ({ name, text: fs.readFileSync(path.join(dir, name), "utf8") }));
  const functions = {};
  for (const f of T.splitFunctions(files)) functions[f.key] = T.fnv1a(T.normalizeBody(f.body));
  return functions;
}

const ref = {
  eebel: { source: "Eebel/SHADOW_MD_EEBEL master (test/fixtures/classic-stock)", functions: fingerprint("classic-stock") },
  vint43: { source: "Vint43's SHADOW_MD, from RealNobser/ShadowMD (test/fixtures/classic-vint43)", functions: fingerprint("classic-vint43") },
};
const out =
  "/* Generated by scripts/build-classic-reference.js from test/fixtures/classic-stock and classic-vint43, do not edit. */\n" +
  "(function (root) {\n" +
  '  "use strict";\n' +
  "  const api = " + JSON.stringify(ref, null, 2).replace(/\n/g, "\n  ") + ";\n" +
  '  if (typeof module !== "undefined" && module.exports) module.exports = api;\n' +
  "  else root.ClassicReference = api;\n" +
  "})(this);\n";
fs.writeFileSync(path.join(here, "lib", "classic-reference.js"), out);
console.log("lib/classic-reference.js: eebel " + Object.keys(ref.eebel.functions).length + ", vint43 " + Object.keys(ref.vint43.functions).length + " functions");
